def load_books():
    rows = []
    with CSV.open(encoding="utf-8") as f:
        for rec in csv.DictReader(f):
            rows.append(rec)
    return rows


def write_one(rec) -> str:
    i = int(rec["id"])
    dept = {"02": "外型", "03": "結構／材料", "04": "生產／CNC"}[rec["role"]]
    core = CORE[i].strip()
    return f"""BjM 訓練講義  {rec['role']}-{int(rec['id']):02d}
部門：{dept}
層次：{rec['foundation_layer']}　練：{rec['trains']}

原典（日後請買正版深讀，本講義不是該書複製品）
  {rec['author']}
  {rec['title']}
  {rec['year_note']}

這本講義要解決什麼
  {rec['why_zh']}

正文
{core}

每天收工前問
  1. 今天哪個判斷對回了這本的層次？
  2. 哪個判斷還在靠感覺？
  3. 明天要量／要試／要改的一件事是什麼？

—— 完 ——
本頁為 BjM 內部原創訓練文本，供廠內精進。
不替代原典，不授權對外出版。
"""


def main():
    books = load_books()
    assert len(books) == 100, len(books)
    assert set(CORE) == set(range(1, 101)), "CORE must be 1..100"
    folders = {
        "02": ROOT / "02_外型" / "訓練" / "書籍",
        "03": ROOT / "03_結構與材料" / "訓練" / "書籍",
        "04": ROOT / "04_生產與CNC" / "訓練" / "書籍",
    }
    for p in folders.values():
        p.mkdir(parents=True, exist_ok=True)
        for old in p.glob("*.txt"):
            old.unlink()
    counts = {"02": 0, "03": 0, "04": 0}
    index_rows = ["id,role,file,title"]
    for rec in books:
        role = rec["role"]
        i = int(rec["id"])
        safe = rec["title"].split("/")[0].strip()
        safe = "".join(ch if ch.isalnum() or ch in " _-" else "" for ch in safe)
        safe = "_".join(safe.split())[:48]
        name = f"B{role}_{i:02d}_{safe}.txt"
        path = folders[role] / name
        text = write_one(rec)
        # hard ban product names
        for ban in ("WAVE", "KOALA", "F180", "波浪椅", "無尾熊", "繪圖櫃", "WAVE-LC", "KOALA-CR"):
            if ban in text:
                raise SystemExit(f"SKU leak in {i}: {ban}")
        path.write_text(text, encoding="utf-8")
        counts[role] += 1
        index_rows.append(f"{i},{role},{name},{rec['title']}")
    (ROOT / "訓練_講義目錄.csv").write_text("\n".join(index_rows) + "\n", encoding="utf-8")
    print("wrote", counts, "total", sum(counts.values()))


if __name__ == "__main__":
    main()
